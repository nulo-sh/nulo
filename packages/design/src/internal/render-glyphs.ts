import { glyphSources } from "../core/glyph-sources"
import type { Glyph } from "../core/glyphs"

/**
 * Pure extractor: turns Tabler's published SVGs into the glyph table `src/core/glyphs.ts` holds.
 * Shared by `scripts/gen-glyphs.ts`, which writes the table, and `glyphs.drift.test.ts`, which pins it.
 * It refuses any attribute or element `Icon.vue` would not draw, so nothing is dropped in silence.
 */

/** Every published file opens with this invisible box; it carries no drawing. */
const NO_OP_BOX = '<path stroke="none" d="M0 0h24v24H0z" fill="none" />'

const FRAME: Readonly<Record<string, string>> = {
	xmlns: "http://www.w3.org/2000/svg",
	width: "24",
	height: "24",
	viewBox: "0 0 24 24",
}

/** The paint `Icon.vue` sets on its root and per path, which each variant must match exactly. */
const PAINT: Readonly<Record<"outline" | "filled", Readonly<Record<string, string>>>> = {
	outline: { fill: "none", stroke: "currentColor", "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round" },
	filled: { fill: "currentColor" },
}

const ATTRIBUTE = /\s+([A-Za-z][\w:-]*)="([^"]*)"/g
const PATH = /<path d="([^"]*)"\s*\/>/g

/** The package specifier of a source in `glyphSources`, resolved through `@tabler/icons`' exports. */
export function tablerSpecifier(source: string): string {
	return source.startsWith("filled/") ? `@tabler/icons/${source}.svg` : `@tabler/icons/outline/${source}.svg`
}

function readAttributes(source: string, text: string): Map<string, string> {
	const attributes = new Map<string, string>()
	for (const [, name, value] of text.matchAll(ATTRIBUTE)) attributes.set(name, value)
	if (text.replace(ATTRIBUTE, "").trim() !== "") throw new Error(`${source}: unreadable root attributes`)
	return attributes
}

function checkRoot(source: string, attributes: Map<string, string>): void {
	const expected = { ...FRAME, ...PAINT[source.startsWith("filled/") ? "filled" : "outline"] }
	for (const [name, value] of attributes) {
		if (name === "class") continue
		if (expected[name] !== value) throw new Error(`${source}: root ${name}="${value}" is not drawn by Icon.vue`)
	}
	for (const name of Object.keys(expected)) {
		if (!attributes.has(name)) throw new Error(`${source}: root lacks ${name}`)
	}
}

/** A space after each `M` or `A` before a number: the milestone scanner reads `M` glued to a decimal as a tag. */
function spaced(d: string): string {
	return d.replace(/([MA])(?=[-.\d])/g, "$1 ")
}

function readPaths(source: string, body: string): string[] {
	const rest = body.replace(NO_OP_BOX, "")
	const paths = [...rest.matchAll(PATH)].map(([, d]) => spaced(d))
	if (rest.replace(PATH, "").trim() !== "") throw new Error(`${source}: holds content other than bare <path d>`)
	if (paths.length === 0) throw new Error(`${source}: draws nothing`)
	if (new Set(paths).size !== paths.length) throw new Error(`${source}: repeats a path`)
	return paths
}

/** One published Tabler SVG as a glyph: outline paths stroked (`s`), a filled icon's paths filled (`f`). */
export function tablerGlyph(source: string, svg: string): Glyph {
	const document = svg.match(/^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/)
	if (!document) throw new Error(`${source}: not one <svg> element`)
	const [, root = "", body = ""] = document
	checkRoot(source, readAttributes(source, root))
	const paths = readPaths(source, body)
	return source.startsWith("filled/") ? { f: paths } : { s: paths }
}

/** Every glyph of `glyphSources`, reading each published file through `read(specifier)`. */
export function tablerGlyphs(read: (specifier: string) => string): Record<string, Glyph> {
	return Object.fromEntries(
		Object.entries(glyphSources).map(([name, source]) => [name, tablerGlyph(source, read(tablerSpecifier(source)))]),
	)
}

const HEADER = `/**
 * GENERATED by scripts/gen-glyphs.ts from src/core/glyph-sources.ts: do not edit; run \`bun run gen:glyphs\`.
 * Tabler Icons 3.49.0 (MIT, recorded in the third-party notices), each path as published but for a space
 * after \`M\`; glyphs.drift.test.ts fails on any divergence. \`s\` paths are stroked, \`f\` paths filled.
 */`

function renderKey(name: string): string {
	return /^[a-z][a-zA-Z0-9]*$/.test(name) ? name : JSON.stringify(name)
}

/** The exact source of `src/core/glyphs.ts` before Biome formats it. */
export function renderGlyphsModule(glyphs: Record<string, Glyph>): string {
	const rows = Object.entries(glyphs).map(([name, glyph]) => {
		const fields = Object.entries(glyph).map(
			([kind, paths]) => `${kind}: [${(paths as string[]).map((d) => JSON.stringify(d)).join(", ")}]`,
		)
		return `\t${renderKey(name)}: { ${fields.join(", ")} },`
	})
	return [
		HEADER,
		"export type Glyph = { readonly s?: readonly string[]; readonly f?: readonly string[] }",
		"",
		`export const glyphs = {\n${rows.join("\n")}\n} as const satisfies Record<string, Glyph>`,
		"",
		"export type GlyphName = keyof typeof glyphs",
		"",
	].join("\n")
}
