<script setup>
import PasswordVisibilityToggle from "@/components/composite/PasswordVisibilityToggle.vue"
import UnlockMethodChoice from "@/components/composite/import/UnlockMethodChoice.vue"
import { newPasswordHint } from "@/utils/password"
import { PHRASE_WORD_COUNT, phraseHint } from "@/utils/recovery-phrase"
/**
 * Section labels carry the visual heading; individual Inputs run
 * label-less to avoid duplicating the heading text. Hints (strength,
 * "Correct" indicator) move under each input via the #bottom slot so
 * they share the same below-input rail the error rail uses.
 */
const props = defineProps({
	method: { type: String, required: true }, // 'seed'
	error: { type: Object, default: () => ({ type: "", title: "", tooltip: "" }) },
	/** The flow's verdict on the typed phrase, the same one its Import button follows. */
	phraseVerdict: { type: Object, default: () => ({ kind: "empty" }) },
	maxPasswordLength: { type: Number, default: 128 },
	/** An import is in flight: the unlock choice it was admitted with stays put. */
	importing: { type: Boolean, default: false },
})

const emit = defineEmits(["secretInput", "passwordInput"])

const seedPhrase = defineModel("seedPhrase", { default: undefined })
const password = defineModel("password", { default: "" })
const repeatedPassword = defineModel("repeatedPassword", { default: "" })
const unlockMethod = defineModel("unlockMethod", { default: "passkey" })

const isPasswordType = ref(true)
const hideCredentials = ref(true)

const passwordHint = computed(() => newPasswordHint(password.value ?? "", repeatedPassword.value ?? ""))
const seedHint = computed(() => phraseHint(props.phraseVerdict))
/** A count still short of 24 is progress; anything else Import refuses reads as an error. */
const seedHintColor = computed(() => {
	const verdict = props.phraseVerdict
	if (verdict.kind === "valid") return "primary"
	return verdict.kind === "count" && verdict.count < PHRASE_WORD_COUNT ? "tertiary" : "txt-danger"
})
</script>

<template>
	<div :class="$style.section">
		<span :class="$style.section_label">Recovery Phrase</span>
		<span :class="$style.note" data-testid="import-seed-note">
			24 words separated by spaces. Use a phrase generated by Nulo. A phrase shared with another wallet lets that software derive your keys.
		</span>

		<Input
			v-if="method === 'seed'"
			v-model="seedPhrase"
			data-testid="import-seed-input"
			@input="emit('secretInput')"
			:type="hideCredentials ? 'password' : 'text'"
			placeholder="Enter recovery phrase"
			autocomplete="off"
		>
			<template #suffix>
				<PasswordVisibilityToggle
					:hidden="hideCredentials"
					subject="recovery phrase"
					data-testid="import-seed-input-visibility-toggle"
					@toggle="hideCredentials = !hideCredentials"
				/>
			</template>
			<template v-if="seedHint" #bottom>
				<Flex align="center" gap="4" :class="$style.hint_row" data-testid="import-seed-hint">
					<Icon v-if="phraseVerdict.kind === 'valid'" name="square-check" size="12" color="green" />
					<Text variant="body" :color="seedHintColor">{{ seedHint }}</Text>
				</Flex>
			</template>
		</Input>
	</div>

	<div :class="$style.section_last">
		<UnlockMethodChoice
			v-model="unlockMethod"
			passwordTestid="import-method-password"
			passkeyTestid="import-method-passkey"
			:disabled="importing"
		>
			<Flex direction="column" gap="12">
				<Input
					v-model="password"
					data-testid="import-password-input"
					:type="isPasswordType ? 'password' : 'text'"
					@input="emit('passwordInput')"
					:maxLength="maxPasswordLength"
					placeholder="Enter new password"
					autocomplete="new-password"
				>
					<template #suffix>
						<PasswordVisibilityToggle
							:hidden="isPasswordType"
							data-testid="import-password-input-visibility-toggle"
							@toggle="isPasswordType = !isPasswordType"
						/>
					</template>
					<template #bottom>
						<Flex align="center" gap="6" :class="$style.hint_row">
							<Icon name="lock" :size="12" color="tertiary" />
							<Text variant="body" color="tertiary">{{ passwordHint }}</Text>
						</Flex>
					</template>
				</Input>
				<Input
					v-model="repeatedPassword"
					data-testid="import-password-confirm-input"
					:type="isPasswordType ? 'password' : 'text'"
					@input="emit('passwordInput')"
					:maxLength="maxPasswordLength"
					placeholder="Repeat password"
					autocomplete="new-password"
				/>
				</Flex>
		</UnlockMethodChoice>

		<Flex v-if="error.type === 'unknown'" align="center" gap="8" :class="$style.unknown_error">
			<span :class="$style.error_tag">Error</span>
			<Flex direction="column" gap="2">
				<Text variant="body" color="secondary">{{ error.title }}</Text>
				<Text v-if="error.tooltip" variant="body" color="secondary" data-testid="import-seed-error-cause">{{ error.tooltip }}</Text>
			</Flex>
		</Flex>
	</div>
</template>

