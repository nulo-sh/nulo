import { Flex, Icon, Input, Text } from "@nulo/design"
import { flushPromises, mount, type VueWrapper } from "@vue/test-utils"
import { createPinia, setActivePinia } from "pinia"
import { afterEach, describe, expect, it, vi } from "vitest"
import { defineComponent, h } from "vue"
import { expectMaskToggle, expectNativeAttrs, nativeInput, pasteInto } from "../../../../tests/helpers/credential-pins"

vi.mock("@/utils/core", () => ({ managers: { profile: { getProfiles: vi.fn(async () => []) } } }))

import { useProfileImportFlow } from "@/composables/useProfileImportFlow"
import ImportSecretForm from "./ImportSecretForm.vue"

const stubs = {
	Flex: { template: "<div><slot /></div>" },
	Text: { props: ["color"], template: "<span :data-color='color'><slot /></span>" },
	Icon: { props: ["name"], template: '<i :data-name="name"></i>' },
	Tooltip: { template: "<div data-tooltip><slot /><slot name='content' /></div>" },
	Transition: { template: "<div><slot /></div>" },
	Input: {
		props: ["modelValue", "label", "placeholder", "type", "error", "maxLength"],
		emits: ["update:modelValue", "input"],
		template: `<input
				:data-testid="$attrs['data-testid']"
				:value="modelValue"
				:type="type"
				:data-error="error"
				@input="$emit('update:modelValue', $event.target.value); $emit('input', $event)"
			/><slot name='right' /><slot name='suffix' /><slot name='labelSuffix' /><slot name='bottom' />`,
	},
}

const baseProps = (over = {}) => ({
	method: "seed",
	error: { type: "", title: "", tooltip: "" },
	maxPasswordLength: 128,
	unlockMethod: "password",
	...over,
})

describe("ImportSecretForm", () => {
	it("a phrase opens on Passkey: its note, and no password field until Password is picked", async () => {
		const { unlockMethod: _, ...props } = baseProps()
		const wrapper = mount(ImportSecretForm, { props, global: { stubs } })
		expect(wrapper.get("[data-testid=import-method-passkey]").attributes("aria-selected")).toBe("true")
		expect(wrapper.find("[data-testid=unlock-method-passkey-note]").exists()).toBe(true)
		expect(wrapper.find("[data-testid=import-password-input]").exists()).toBe(false)
		await wrapper.get("[data-testid=import-method-password]").trigger("click")
		expect(wrapper.emitted("update:unlockMethod")).toEqual([["password"]])
	})

	it("renders phrase input + new+confirm password fields when Password is picked", () => {
		const wrapper = mount(ImportSecretForm, { props: baseProps(), global: { stubs } })
		expect(wrapper.text()).toContain("Recovery Phrase")
		expect(wrapper.text()).toContain("How you'll unlock Nulo")
		expect(wrapper.find("[data-testid=unlock-method-passkey-note]").exists()).toBe(false)
		// new + confirm
		expect(wrapper.find("[data-testid=import-password-input]").exists()).toBe(true)
		expect(wrapper.find("[data-testid=import-password-confirm-input]").exists()).toBe(true)
	})

	it("exposes ONLY the seed input testid (plain/encrypted key inputs are gone)", () => {
		const seed = mount(ImportSecretForm, { props: baseProps({ method: "seed" }), global: { stubs } })
		expect(seed.find("[data-testid=import-seed-input]").exists()).toBe(true)
		expect(seed.find("[data-testid=import-private-key-input]").exists()).toBe(false)
		expect(seed.find("[data-testid=import-public-key-input]").exists()).toBe(false)
	})

	it("emits secretInput when typing into the phrase field", async () => {
		const wrapper = mount(ImportSecretForm, { props: baseProps({ method: "seed" }), global: { stubs } })
		await wrapper.find("[data-testid=import-seed-input]").trigger("input")
		expect(wrapper.emitted("secretInput")).toBeTruthy()
	})

	it("emits passwordInput when typing into the password field", async () => {
		const wrapper = mount(ImportSecretForm, { props: baseProps(), global: { stubs } })
		await wrapper.find("[data-testid=import-password-input]").trigger("input")
		expect(wrapper.emitted("passwordInput")).toBeTruthy()
	})

	it("shows the unknown-error banner when error.type === 'unknown'", () => {
		const wrapper = mount(ImportSecretForm, {
			props: baseProps({ error: { type: "unknown", title: "Boom", tooltip: "" } }),
			global: { stubs },
		})
		expect(wrapper.text()).toContain("Error")
		expect(wrapper.text()).toContain("Boom")
	})

	it("states the recovery-phrase note as text between the label and the field, with no ⓘ", () => {
		const wrapper = mount(ImportSecretForm, { props: baseProps({ method: "seed" }), global: { stubs } })
		const note = wrapper.get("[data-testid=import-seed-note]")
		expect(note.text()).toBe(
			"24 words separated by spaces. Use a phrase generated by Nulo. A phrase shared with another wallet lets that software derive your keys.",
		)
		const section = note.element.parentElement
		expect(section?.firstElementChild?.textContent).toBe("Recovery Phrase")
		expect(section?.firstElementChild?.nextElementSibling).toBe(note.element)
		expect(note.element.nextElementSibling).toBe(wrapper.get("[data-testid=import-seed-input]").element)
		expect(wrapper.find("[data-tooltip]").exists()).toBe(false)
		expect(wrapper.find('[data-name="info"]').exists()).toBe(false)
	})

	it.each([
		[{ kind: "valid" }, "Correct", true, "primary"],
		[{ kind: "count", count: 23 }, "23 of 24 words", false, "tertiary"],
		[{ kind: "count", count: 25 }, "25 words. A phrase has 24.", false, "txt-danger"],
		[{ kind: "word", position: 5 }, "Word 5 is not in the word list.", false, "txt-danger"],
		[{ kind: "checksum" }, "A word is wrong or out of order.", false, "txt-danger"],
	])("the phrase's verdict %o reads %j under the field, with the check only when valid", (phraseVerdict, line, checked, color) => {
		const wrapper = mount(ImportSecretForm, { props: baseProps({ method: "seed", phraseVerdict }), global: { stubs } })
		const hint = wrapper.get("[data-testid=import-seed-hint]")
		expect(hint.text()).toBe(line)
		expect(hint.get("span").attributes("data-color")).toBe(color)
		expect(wrapper.find('[data-name="square-check"]').exists()).toBe(checked)
	})

	it.each([{ kind: "empty" }, { kind: "pending" }])("a verdict of %o shows no line", (phraseVerdict) => {
		const wrapper = mount(ImportSecretForm, { props: baseProps({ method: "seed", phraseVerdict }), global: { stubs } })
		expect(wrapper.find("[data-testid=import-seed-hint]").exists()).toBe(false)
	})

	it("an import failure shows its cause under its title, as text", () => {
		const wrapper = mount(ImportSecretForm, {
			props: baseProps({ error: { type: "unknown", title: "Import failed", tooltip: "<b>Passkey input already belongs</b>" } }),
			global: { stubs },
		})
		const cause = wrapper.get("[data-testid=import-seed-error-cause]")
		expect(cause.text()).toBe("<b>Passkey input already belongs</b>")
		expect(cause.find("b").exists()).toBe(false)
	})
})

describe("ImportSecretForm — the import flow's own verdict", () => {
	/** The form and an Import button wired to one real flow, as both import pages wire them. */
	const Wired = defineComponent({
		setup() {
			const flow = useProfileImportFlow({ completeImport: vi.fn(), showErrorLog: vi.fn(), openToast: vi.fn() })
			flow.unlockMethod.value = "password"
			flow.password.value = "password123"
			flow.repeatedPassword.value = "password123"
			return () => [
				h(ImportSecretForm, {
					method: "seed",
					error: flow.error.value,
					phraseVerdict: flow.phraseVerdict.value,
					seedPhrase: flow.seedPhrase.value,
					"onUpdate:seedPhrase": (v: string) => {
						flow.seedPhrase.value = v
					},
					password: flow.password.value,
					repeatedPassword: flow.repeatedPassword.value,
					unlockMethod: flow.unlockMethod.value,
				}),
				h("button", { "data-testid": "import-seed-submit-btn", disabled: !flow.isAllowedToImportBySeedPhrase.value }),
			]
		},
	})
	const VALID = `${"abandon ".repeat(23)}art`

	it.each([
		["a bad checksum", "abandon ".repeat(24).trim(), "A word is wrong or out of order.", true],
		["a padded, double-spaced valid phrase", `  ${VALID.replaceAll(" ", "  ")} `, "Correct", false],
	])("%s: the line and the button agree", async (_, phrase, line, disabled) => {
		setActivePinia(createPinia())
		const wrapper = mount(Wired, { global: { stubs } })
		await wrapper.get("[data-testid=import-seed-input]").setValue(phrase)
		await vi.waitFor(async () => {
			await flushPromises()
			expect(wrapper.find("[data-testid=import-seed-hint]").exists()).toBe(true)
		})
		expect(wrapper.get("[data-testid=import-seed-hint]").text()).toBe(line)
		expect(wrapper.text().includes("Correct")).toBe(line === "Correct")
		expect((wrapper.get("[data-testid=import-seed-submit-btn]").element as HTMLButtonElement).disabled).toBe(disabled)
		wrapper.unmount()
	})
})

describe("ImportSecretForm — credential controls, real Input", () => {
	const mounted: VueWrapper[] = []
	afterEach(() => {
		for (const w of mounted.splice(0)) w.unmount()
	})
	const mountReal = () => {
		const w = mount(ImportSecretForm, {
			props: baseProps(),
			attachTo: document.body,
			global: { components: { Flex, Icon, Input, Text } },
		})
		mounted.push(w)
		return w
	}
	const SEED = "import-seed-input"
	const PAIR = ["import-password-input", "import-password-confirm-input"]

	it("the phrase toggle masks the phrase alone", async () => {
		await expectMaskToggle(mountReal(), {
			toggle: "import-seed-input-visibility-toggle",
			field: SEED,
			drives: [SEED],
			others: PAIR,
			subject: "recovery phrase",
		})
	})

	it("the password toggle masks both password fields and never the phrase", async () => {
		await expectMaskToggle(mountReal(), {
			toggle: "import-password-input-visibility-toggle",
			field: PAIR[0],
			drives: PAIR,
			others: [SEED],
		})
	})

	it("native attributes per field, and nothing is focused on mount", () => {
		const w = mountReal()
		expectNativeAttrs(w, SEED, { autocomplete: "off", autocapitalize: null, autocorrect: null })
		for (const id of PAIR) expectNativeAttrs(w, id, { autocomplete: "new-password", autocapitalize: null, autocorrect: null })
		expect(document.activeElement).toBe(document.body)
	})

	it("a paste into the phrase is native; a paste into a password field is capped at 128", () => {
		const w = mountReal()
		expect(pasteInto(nativeInput(w, SEED), "x".repeat(300))).toBe(false)
		expect(pasteInto(nativeInput(w, PAIR[0]), "y".repeat(130))).toBe(true)
		expect(w.emitted("update:password")?.at(-1)).toEqual(["y".repeat(128)])
	})
})
